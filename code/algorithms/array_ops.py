# Массив (list в Python): элементы лежат в памяти подряд, доступ по индексу — O(1).
# Ниже — как устроены основные операции и почему у них такая сложность.

def get(arr, i):
    """arr[i]. Время O(1): адрес = начало + i · размер ячейки. Память O(1)."""
    return arr[i]


def append(arr, x):
    """Добавить в конец. Время O(1) амортизированно: обычно есть свободная ячейка;
    если нет — Python выделяет больший блок и копирует всё (O(n)), но редко."""
    arr.append(x)


def insert(arr, i, x):
    """Вставить на позицию i — то, что делает list.insert, вручную.
    Время O(n): все элементы правее i сдвигаются на одну позицию вправо. Память O(1)."""
    arr.append(None)                         # место под последний элемент
    for k in range(len(arr) - 1, i, -1):     # сдвигаем хвост вправо, начиная с конца
        arr[k] = arr[k - 1]
    arr[i] = x


def delete(arr, i):
    """Удалить элемент с позиции i — то, что делает list.pop(i), вручную.
    Время O(n): все элементы правее i сдвигаются влево. pop() с конца — O(1)."""
    val = arr[i]
    for k in range(i, len(arr) - 1):
        arr[k] = arr[k + 1]
    arr.pop()                                # последняя ячейка теперь лишняя
    return val


def search(arr, x):
    """Поиск значения: в неотсортированном массиве — линейный, O(n).
    В отсортированном можно бинарным — O(log n)."""
    for i, v in enumerate(arr):
        if v == x:
            return i
    return -1
