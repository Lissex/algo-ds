def insertion_sort(arr):
    """Сортировка вставками (на месте, устойчивая).
    Берём очередной элемент и сдвигаем его влево, пока слева стоят большие.
    Время: O(n²) в худшем и среднем, O(n) в лучшем (массив уже отсортирован).
    Память O(1)."""
    for i in range(1, len(arr)):
        key = arr[i]                         # элемент, который вставляем
        j = i - 1
        while j >= 0 and arr[j] > key:       # строго > — равные не переставляем (устойчивость)
            arr[j + 1] = arr[j]              # сдвигаем больший элемент вправо
            j -= 1
        arr[j + 1] = key                     # ставим key в освободившееся место
