def bubble_sort(arr):
    """Сортировка пузырьком (на месте, устойчивая).
    Проходим по массиву и меняем соседей, если они стоят неправильно.
    После каждого прохода самый большой элемент «всплывает» в конец.
    Время: O(n²) в худшем и среднем, O(n) в лучшем — благодаря флагу swapped.
    Память O(1)."""
    n = len(arr)
    for i in range(n - 1):
        swapped = False
        for j in range(n - 1 - i):           # последние i элементов уже на своих местах
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True
        if not swapped:                      # за проход ни одного обмена — массив отсортирован
            break
