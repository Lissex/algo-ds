def selection_sort(arr):
    """Сортировка выбором (на месте).
    На каждом шаге ищем минимум в неотсортированной части и ставим его в начало этой части.
    Время O(n²) всегда: поиск минимума — n-1, n-2, ..., 1 сравнений.
    Память O(1): только индексы, обмен на месте."""
    n = len(arr)
    for i in range(n - 1):
        min_idx = i                          # считаем, что минимум — первый неотсортированный
        for j in range(i + 1, n):
            if arr[j] < arr[min_idx]:
                min_idx = j                  # нашли меньше — запоминаем индекс
        arr[i], arr[min_idx] = arr[min_idx], arr[i]   # ставим минимум на место i
