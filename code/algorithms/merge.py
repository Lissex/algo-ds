def merge(a, b):
    """Слияние двух отсортированных массивов в один отсортированный.
    Два указателя i и j: каждый раз берём меньший из a[i] и b[j].
    Время O(n + m): каждый элемент берём ровно один раз.
    Память O(n + m): новый массив-результат."""
    result = []
    i = j = 0
    while i < len(a) and j < len(b):
        if a[i] <= b[j]:                     # <= — при равенстве берём из a (устойчивость)
            result.append(a[i])
            i += 1
        else:
            result.append(b[j])
            j += 1
    result.extend(a[i:])                     # остаток одного из массивов уже отсортирован
    result.extend(b[j:])
    return result
