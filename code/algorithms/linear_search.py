def linear_search(arr, target):
    """Линейный поиск: проверяем элементы по очереди. Возвращает индекс первого вхождения или -1.
    Работает на любом (в том числе неотсортированном) массиве.
    Время: O(n) в худшем и среднем, O(1) в лучшем (target первый). Память O(1)."""
    for i in range(len(arr)):
        if arr[i] == target:
            return i
    return -1
